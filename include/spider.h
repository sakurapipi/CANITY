/*
 * Canity — 缚丝蛛（v2.4.1 第 5~6 轮）
 *
 * ==================================================================
 * 定位
 * ------------------------------------------------------------------
 * 它**不是**又一只追杀玩家的怪，而是改变行动节奏的控制型敌人：
 *   吐丝 → 限制移动 → 迫使玩家挣脱 → 为其它怪创造追击机会
 *
 * 硬约束：
 *   · 不造成任何伤害（不掉血、不掉 SAN、不置 tookDamage）
 *   · 不杀死玩家
 *   · 超时自动释放，绝不会把人永久困住
 *   · 与抱脸虫共用控制层，不会同时生效
 *   · 每层最多 1 只，不写入存档
 * ==================================================================
 */
#ifndef CANITY_SPIDER_H
#define CANITY_SPIDER_H

/* 状态（渲染与测试都要读） */
enum {
    SPIDER_IDLE = 0,
    SPIDER_PATROL,
    SPIDER_AIM,        /* 前摇：抬起前肢，有声音提示 */
    SPIDER_FIRE,       /* 吐丝瞬间 */
    SPIDER_COOLDOWN
};

#define SPIDER_MIN_LEVEL      4
/* ==================================================================
 * 2026-11-06（用户要求）：**蜘蛛正式入局，频率按深度走**
 * ------------------------------------------------------------------
 * 用户原话：「可以把它加入局内了，然后频率的话你根据平均数值来定」。
 *
 * 参考本作其它怪的密度（听声鬼每层 1 只、偷电怪第 3 层起 1 只、
 * 追光鬼 2 只常驻），蜘蛛作为**控制型**威胁不该每层都来，
 * 也不该稀有到玩家忘了它存在。取一条随深度上升的曲线：
 *
 *   出现率 = BASE + (层数 - 起始层) * STEP，夹在 [BASE, CAP]
 *   第 4 层 20% → 第 6 层 30% → 第 10 层 50% → 第 12 层起 60%
 *
 * 平均下来大约是「每 2~3 层遇到一次」，和追光鬼/听声鬼的压迫感错开，
 * 既不会盖过常驻怪的存在感，也不会让玩家忘了要提防。
 * ================================================================ */
#define SPIDER_APPEAR_BASE    20     /* 起始层的出现率（百分比） */
#define SPIDER_APPEAR_STEP    5      /* 每深一层 +5% */
#define SPIDER_APPEAR_CAP     85     /* 上限 */
#define SPIDER_AIM_TIME       0.8f   /* 前摇（用户要求 0.7~1.0） */
#define SPIDER_RANGE          7.0f   /* 射程（格）；保留视线、前摇和躲避窗口 */
#define SPIDER_COOLDOWN_TIME  8.0f
#define SPIDER_MOVE_SPEED     0.85f  /* 远慢于玩家 2.0 */
/* ==================================================================
 * 2026-11-06（用户要求）：**蛛网挣脱重做**
 * ------------------------------------------------------------------
 * 用户原话：「可以控制住你 5 秒钟，然后你连续戳的话，每点一次就可以
 *           减 0.5 秒的控制时间，解除上限是 2 秒钟。就是说你再怎么解除，
 *           最快也要等 2 秒钟」。
 *
 * 所以不是"戳够几下就放"，而是"把 5 秒削到 2 秒，然后只能等"。
 * ================================================================ */
#define SPIDER_WEB_WINDOW     5.0f    /* 初始控制时长 */
#define SPIDER_WEB_REDUCE     0.5f    /* 每次按键削减 */
/* 2026-11-06（用户实测）：下限 2.0 -> 1.0。
   「不然玩家手感会没有」—— 戳到 2 秒还要再等 2 秒确实太长。 */
#define SPIDER_WEB_MIN        1.0f    /* 下限：再快也要等这么久 */

/* 2026-11-06（用户要求）：扳手砸中蜘蛛 → 它消失，30 秒内不再刷新 */
#define SPIDER_RESPAWN_COOLDOWN 30.0f

void  SpiderReset(void);
/* 被扳手砸中：当场消失，并进入 30 秒不刷新冷却 */
void  SpiderDispel(void);
/* 是否处于"刚被砸掉"的冷却里（测试与生成用） */
float SpiderRespawnCd(void);
int   SpiderTrySpawn(int level);    /* 返回 1 = 本层有蜘蛛 */
void  SpiderTick(float dt);
int   SpiderActive(void);
int   SpiderState(void);
float SpiderX(void);
float SpiderY(void);

#endif /* CANITY_SPIDER_H */

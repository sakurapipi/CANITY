/* 铁律十二 [AD-12]：按执行路径验证图层，不把行号当充分证据。
 * 执行：确认调用入口、条件分支、写入缓冲以及最后的 StretchDIBits / BitBlt。
 * 应覆盖某遮罩的提示，在该遮罩之后绘制；应被遮罩挡住的场景仍在它之前。
 * 验收：需要呈现的像素写入都发生在对应缓冲被提交之前。
 * 行号可帮助定位，但不同函数、分支与渲染路径中的行号不能直接证明层级正确。
 */

/* 铁律十三 [AD-13]：层级优先级与空间避让都要定义。
 * 执行：为常驻 HUD、事件提示、藏身面板、锁盘、出口选择分配内容区域。
 * 验收：同时出现时，关键文字不重叠、不贴边；背景复杂处仍可读。
 * 普通 toast 给模态操作让路；购买／失败等相关反馈应在当前面板内可见。
 * 中央可供 QTE、出口选择等主要任务使用；不再要求“任何时候中央只能有遮罩”。
 */

/* 铁律十四 [AD-14]：文案表达实际生效的数据。
 * 执行：冷却、次数、折扣、价格、成本与效果数字取自实际计算入口／数据表。
 * 商品名取商品 ID，不能取显示行号；技能总价包含实际收取的全部金币部分。
 * 验收：显示价等于扣款价；预览等于同状态下的结算；参数变化后描述同步。
 * 静态叙述可保留文案；带数值的描述应由同一数据定义生成或有对应一致性检查。
 * 原来“等 bench 重做再处理”的暂缓说明已过时，不能继续给新文案开豁免。
 */

/* 铁律十五 [AD-15]：状态换色只改约定部件。
 * 执行：使用区域／调色板映射，保留主体的轮廓、阴影、高光与材质。
 * 验收：固定姿态、光照、距离对照时，变化集中在指定部件。
 * 拾荒者的财物、守门人的眼部不能带着全身一起染黄／染红。
 * 动画或光照不同的帧不做“其余像素必须完全相同”的机械比较。
 */

/* 铁律十六 [AD-16]：形态变化换变体，颜色变化换部件色。
 * 执行：姿态／头部结构变化选对应 sprite；换色不复用成整身 tint。
 * 验收：旧脸、旧眼睛没有叠在新变体上；状态切回后也正确。
 * 调色 key 的每个渲染分支都有替代色或明确的安全回退；不能裸露洋红 key。
 */

/* 铁律十七 [AD-17]：固定可复用的建模工序。
 * 执行：1—3 个主要特征 → 黑色剪影 → 少量主体明暗色 → 材质 → 状态变体。
 * 改某个 kind 前，查全部 kind / pose 分支和后续覆盖，避免通用 else 再画旧脸。
 * 验收：精灵导出检查形状／颜色，实机场景检查光照／比例／深度，两者互补。
 * 主体以约 4—5 档明暗为起点；这是设计预算，不是最终画面只能有五种 RGB。
 * 扫描应只禁止该变体不该出现的色和未映射 key，不能禁止所有怪共有的绿色。
 * CANITY_DUMP 可作诊断入口；它输出的素材不是已经完成场景验收的证明。
 */


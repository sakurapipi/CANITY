/* 铁律二十五 [AD-25]：文字按实际像素测量，先保证决策信息完整。
 * 执行：测量使用最终字体、字号、语言与缩放；UTF-8 截断只在完整码点边界发生。
 * 宽度扣除侧栏、图标、数值列、滚动条与边距，再决定换行、详情展开或省略。
 * 验收：名称、等级、总价、可用次数、操作键仍能理解；长说明另有可见详情。
 * 空间不够时不能把成本裁掉，也不能用“最多 80 字节”冒充像素排版。
 */

/* 铁律二十六 [AD-26]：操作反馈以实际结果为准。
 * 执行：购买返回值、钱包扣款、节点拥有状态与成功音效走同一结果分支。
 * 验收：钱不够、缺前置、已满级、顶点互斥、冷却中均有当前界面可见的反馈。
 * 成功时数值和状态随之改变；失败不能显示“已安装”或播放成功音效。
 * 反馈不是一条后台日志；需验证玩家所在页面是否真的绘制了它。
 */

/* 铁律二十七 [AD-27]：动作动画与生效窗口使用同一时间轴。
 * 执行：扳手等动作明确起手、有效帧、收势；每个目标每次挥击只结算一次。
 * 验收：有效帧内进入范围也能命中，下一次挥击清除上次命中记录。
 * 次数、冷却、受击效果、声音与命中结果一致；进入游戏不因残留按键误消耗。
 * 本作击退不击杀；强化改变距离、硬直和记忆，不恢复旧伤害系统。
 */

/* 铁律二十八 [AD-28]：模态界面有明确的时间与输入边界。
 * 执行：出口选择、商店、三选一、锁盘分别说明哪些逻辑冻结、哪些表现继续。
 * 验收：允许暂停的选择期间，不会因后台怪物推进而受到不公平损失。
 * 技能与遗物同时到期要排队；关闭面板后的鼠标／按键边沿需重新同步。
 * 不能只给死亡加保护，却让追逐、抓捕、资源或冷却在错误状态继续推进。
 */

/* 铁律二十九 [AD-29]：验证证据分级，未看到就保留未验证状态。
 * 执行：分别记录源码接线、编译、运行时断言、精灵检查、真实界面走查。
 * 验收：自动推进五关叫“流程模拟”；几何无相交叫“布局断言”；都不能写成完整手玩。
 * 本轮 800×600、806×640、1280×720、1920×1080 几何断言已覆盖；
 * 实际低内部渲染分辨率、DPI、中英文长文本和全部模态组合仍需视觉检查。
 * 自动检查次数不是独立功能数；控制工具中断后，不补写不存在的截图结论。
 */

/* 铁律三十 [AD-30]：先定位真实调用路径，再决定重写范围。
 * 执行：显示消失／崩溃时，查入口、状态、条件、实际绘制函数与异常证据。
 * 验收：能说明根因和触发条件；复现后再改能解释症状的最小范围。
 * ShopPriceAt 自递归曾引起栈溢出，不能仅凭“打开商店会崩”认定布局递归。
 * 空崩溃日志是线索，不足以单独证明栈耗尽；调用栈或等价诊断才可确认。
 */


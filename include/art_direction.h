/*
 * Canity — 审美设计规范（ART DIRECTION）
 * =====================================
 * 这个文件是**规范文档**，不是代码。放在 include/ 里，是为了让任何人改怪物外观前
 * 一定会先看到它。新增怪物时，对照下面每一条检查，过不了就不许合并。
 *
 * 来源：Creature Design · Sharp Edges
 *       https://github.com/omer-metin/skills-for-antigravity/blob/main/skills/creature-design/references/sharp_edges.md
 *       2026-11-01 调研后整理。
 *
 * ── 为什么要有这一页 ──────────────────────────────────────────────
 * 我们新做的三只怪，前两版都被打回：
 *   第一版：用椭圆拼身体 → 用户评价「长得都很奇怪」「像道具」
 *   第二版：复用听声怪精灵只换颜色 → 用户评价「同一套模型特色在哪里」
 * 两次都不是「不好看」，是**违反了下面这些可以量化检查的规则**。
 */

#ifndef CANITY_ART_DIRECTION_H
#define CANITY_ART_DIRECTION_H

/* ================================================================== */
/* 铁律一：BLACK FILL TEST（最重要，一票否决）                          */
/* ================================================================== */
/*
 * 做法：把怪物设计填成纯黑 → 缩到 32×32 → 还能认出是哪一只吗？
 *
 * 过不了的典型症状（调研原文）：
 *   "It's just an oval or generic shape."
 *   "Your creature has lots of detail but fills with black."
 *
 * 我们的椭圆方案就是典型失败案例：填黑之后是一个蛋。
 */

/* ================================================================== */
/* 铁律二：每只怪必须有 LANDMARKS（独特凸起）                           */
/* ================================================================== */
/*
 * 光有「身体 + 头 + 四肢」不够 —— 所有生物都长这样。
 * 必须有一个**别人没有的凸起**，让剪影一眼可辨：
 *     角 / 尾 / 翼 / 背包 / 长臂 / 提灯 / 长袍
 *
 * 同时必须有 NEGATIVE SPACE（肢体和躯干之间的空隙），
 * 否则剪影会糊成一个实心块。
 *
 * 还必须有 ASYMMETRY（不对称）—— 完美镜像 = 没有读感。
 */

/* ================================================================== */
/* 铁律三：RULE OF THREE —— 每只最多三个主要特征                        */
/* ================================================================== */
/*
 * 超过三个就从「有特色」变成「视觉噪声」（creature-overdesign-syndrome）。
 * 三个特征必须各自独立可读，不是同一个特征的三种装饰。
 */

/* ================================================================== */
/* 铁律四：体型要说出「它怎么动」                                       */
/* ================================================================== */
/*
 * SMALL  creature → 细肢、大头、快
 * MEDIUM creature → 比例均衡
 * LARGE  creature → 粗柱腿、小头、慢
 *
 * 违反这条，玩家会本能觉得「不对」但说不出为什么。
 *
 * 本项目对照表：
 *   清道夫 1.0 格/秒（最慢）  → 重、拖沓、长臂垂地
 *   拾荒者 1.6 格/秒          → 矮壮、背重物、蹒跚
 *   守门人 0.7 格/秒（最慢）  → 直立、庄重、提灯
 *   （视觉重量必须和实际移速一致，否则玩家会做错判断）
 */

/* ================================================================== */
/* 铁律五：恐怖不要卡通                                                */
/* ================================================================== */
/*
 * 调研原文（FOR HORROR）：
 *   Eyes:       Wrong (too many, too human, or absent)
 *   Proportions: Violated (wrong size relationships)
 *   Shapes:     Angular, sharp, asymmetric
 *
 * ✗ 错误示范：两个大小一致、水平并排、位置对称的方块眼睛 —— 那是卡通
 * ✓ 正确方向：只长一只眼 / 三只横排 / 完全没有眼 / 眼睛位置偏移
 */

/* ================================================================== */
/* 铁律六：LINEUP TEST —— 并排看剪影                                    */
/* ================================================================== */
/*
 * 把所有怪并排成纯黑剪影，能各自叫出名字吗？
 * 认不出来的那只 = 剪影不合格。
 *
 * 训练营（10 Tutorial）已经做成平层开放空间，五只怪一字排开
 * —— 那就是我们的 LINEUP TEST 场地。
 */

/* ================================================================== */
/* 本作六只怪的剪影规格（改动前对照这张表）                             */
/* ================================================================== */
/*
 * SOUND HUNTER 听声怪   ✅ 基准，已验证「设计成功」
 *                      瘦高人形 / 无眼 / 咧开的牙齿下颌 / 冷灰蓝
 *
 * LIGHT BEAST  追光怪   ✅ 基准，已验证「设计成功」
 *                      更细长 / 一对又大又亮的眼睛 / 偏白
 *
 * FACE JUMPER  爆脸虫   ✅ 保留（QTE 弹脸，走屏幕空间绘制）
 *
 * THE COLLECTOR 拾荒者
 *   地标：背上一个大麻袋（最高点超过头顶）
 *   特征：① 大麻袋 ② 极短的腿 ③ 一只手护着口袋
 *   不对称：口袋偏左肩，身体向右倾
 *   眼睛：**只有一只**（独眼）
 *   比例：头小、身宽、腿短 —— 「负重搬运者」
 *
 * THE SCAVENGER 清道夫
 *   地标：两条手臂垂到地面以下（超过脚）
 *   特征：① 长臂垂地 ② 驼背前倾 ③ 腿细长、膝盖外翻
 *   不对称：一条手臂比另一条长
 *   眼睛：**没有眼睛**
 *   比例：极高极瘦 —— 「慢但一定会到场」
 *
 * THE WARDEN 守门人
 *   地标：一只手提着一盏灯（剪影上唯一的圆形）
 *   特征：① 提灯 ② 下半身整块长袍看不到腿 ③ 肩膀极宽平直
 *   不对称：灯只在右侧
 *   眼睛：**三只横排**（比正常多）
 *   比例：最矮最宽、站姿笔直 —— 「守门人」
 */

/* ================================================================== */
/* 新增怪物时的检查清单                                                */
/* ================================================================== */
/*
 * [ ] 填黑缩到 32×32 还认得出吗？
 * [ ] 有独特地标（凸起）吗？
 * [ ] 有负空间（肢体和躯干之间有缝）吗？
 * [ ] 不对称吗？
 * [ ] 主要特征 ≤ 3 个吗？
 * [ ] 体型和它的移速对得上吗？
 * [ ] 眼睛是「不对」的（独眼 / 多眼 / 无眼 / 偏移）吗？
 * [ ] 和另外五只并排，剪影互不混淆吗？
 */

#endif /* CANITY_ART_DIRECTION_H */

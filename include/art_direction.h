/* ================================================================== */
/* 铁律十：升级「光照」不等于「换掉形状」（2026-11-01 踩坑记录）          */
/* ================================================================== */
/*
 * 事故：
 *   用户要求「箱子 / 藏身点 / 配电箱 也加仿 3D 效果」。
 *   我的做法是**用程序化方盒 DrawPropBox() 替换掉三个烘焙精灵**。
 *   用户反馈：**「你要保留特色呀，回退先吧。垃圾桶还是原来那个，箱子就是正常的小箱子。」**
 *
 * 错在哪：
 *   这三个道具本来就是三种不同的东西 ——
 *     垃圾桶    是**圆的**（铁皮桶，有桶口和桶身）
 *     箱子      是**木的**（有木板缝、有盖子、翻过之后盖子掀开）
 *     配电箱    是**金属机柜**（方形、有面板、有开关）
 *   我给它们套了同一个方盒子模板 + 换配色，
 *   **等于把三个各有形状的东西压成同一种几何体**，
 *   违反铁律二（LANDMARKS）——「每样东西必须有自己独特的形状特征」。
 *
 * 正确做法：
 *   **改烘焙，不改渲染。**
 *     · 烘焙精灵（sprites.c 的 BakeProp / Bake*）决定**形状** → 保持不动
 *     · 在烘焙时把斜角 / 内凹 / 板缝 画进贴图里 → 形状不变，明暗变好
 *     · 渲染层继续用 DrawBakedProp() 直出 → 一行不改
 *
 *   这样「特色」和「立体感」不冲突：
 *     圆的还是圆的，木的还是木的，只是受光更讲究了。
 *
 * 判断标准：
 *   **做完之后，把新旧图并排，能不能一眼看出「这是同一个东西，只是更好看了」？**
 *   如果看成了「另一个东西」→ 做错了。
 */

/* ================================================================== */
/* 铁律十一：尺度与像素密度必须一致（调研结论）                          */
/* ================================================================== */
/*
 * 来自 2.5D 像素画项目的制作经验（Sepulvia / IndieDB）：
 *
 *   "Two of the most important concepts are Scale and Pixel resolution.
 *    If these two remain consistent, you're already more than halfway
 *    to a good final product."
 *
 * 翻译：**尺度和像素密度一致了，就已经完成一半了。**
 *
 * 对本项目的含义：
 *   · 所有烘焙精灵的画布尺寸、像素密度必须一致（现在都是定长画布，✓）
 *   · 同一个世界里，一个箱子 / 一个垃圾桶 / 一个人，**相对高度要有比例感**
 *       听声怪  halfH 0.86
 *       拾荒者  halfH 0.82（矮胖）
 *       清道夫  halfH 0.96（高瘦）
 *       守门人  halfH 0.92
 *       箱子    halfH 0.42   ← 约人的一半
 *       垃圾桶  halfH 0.46
 *       配电箱  halfH 0.52
 *       出口    halfH 1.05（通电时最高，因为它是门）
 *   · **新增物件先量一下 halfH**，别凭感觉给。
 */

/* ================================================================== */
/* 道具「加立体感」的正确工序                                            */
/* ================================================================== */
/*
 * 步骤（下次照这个做）：
 *
 *   ① 先看原烘焙函数是怎么画这个道具的（sprites.c）
 *   ② **不动形状**，只往贴图里加三层：
 *        · 斜角    上/左边缘 1~2 像素提亮，下/右边缘压暗
 *        · 内凹    面板内部再嵌一层，上壁暗下壁亮
 *        · 板缝/纹理  按材质来（木=竖纹、铁=横纹、布=斜纹）
 *   ③ 重新烘焙，渲染层一行不改
 *   ④ 新旧图并排对比：形状没变，只是好看了 → 通过
 *
 * ❌ 不要做的事：
 *    · 不要在渲染层用程序化几何**替换**已有精灵
 *    · 不要把不同材质的东西套同一个模板
 *    · 不要为了「统一风格」抹掉各自的形状特征
 */


/* ================================================================== */
/* 铁律十二：绘制顺序只有一个**正确区间**，而且必须用行号断言           */
/* ================================================================== */
/*
 * 2026-11-01 连续踩两次坑，两次都是「往 pixels 写的位置不对」：
 *
 *   第一次：把事件提示挪到 RenderFrame 末尾想压住藏身遮罩
 *           → 还是被遮罩盖住（遮罩比它更晚）
 *   第二次：为躲开遮罩，又往后挪
 *           → **文本彻底消失**（挪到了 StretchDIBits 之后）
 *
 * 上一版规则写的是「必须在 blit 之前」——
 * 这条**看着对，但没用**：它只说了「不能太晚」，没说「也不能太早」。
 *
 * ── 正确的说法 ─────────────────────────────────────────────
 *
 *   任何往 pixels 写的东西，只允许落在这一段里：
 *
 *     最后一个遮罩（BlendRectWin / FrameRectWin 的遮罩层）
 *        ↓
 *     【这里】←—— 只有这一点
 *        ↓
 *     StretchDIBits / BitBlt
 *
 *   太早 → 被后画的遮罩盖住
 *   太晚 → 改的是已经贴到屏幕的缓冲，等于没画
 *
 * ── 验证方法（必须做，不许凭感觉）────────────────────────
 *
 *   ① grep -n "StretchDIBits" src/ui.c       记下行号 B
 *   ② grep -n "目标绘制的调用"   src/ui.c       记下行号 D
 *   ③ 断言 D < B                             —— 保证画得出来
 *   ④ grep -n "BlendRectWin" 中属于遮罩的行      全记下
 *      断言 D > 它们全部                       —— 保证盖得住
 *
 *   两条都过才算对。少任何一条，就是上面那两次犯的错。
 *
 * ── 通用结论 ───────────────────────────────────────────────
 *
 *   「看起来应该在上面」不是依据。**行号才是依据。**
 *   任何「让 X 盖住 Y」的需求，先拿两条行号，再决定插在哪，
 *   插完再查一次行号确认。
 */

/* ================================================================== */
/* 铁律十三：不同层级的 UI，放的位置和字号都不一样                       */
/* ================================================================== */
/*
 *   层级            放哪                     字号
 *   ───────────────────────────────────────────────────────
 *   场景 / 道具      屏幕中                    —
 *   HUD 常驻信息     四角                      标准
 *   功能遮罩         覆盖整个屏幕               —
 *   事件提示         有遮罩时 → **角落**       小号（scale 1）
 *                    无遮罩时 → 上方居中       标准
 *
 * 为什么遮罩出现时提示要变小、挪角落：
 *   遮罩的作用是「限制视野」，那时屏幕中央是**唯一要看的地方**。
 *   提示占正中央 = 和遮罩抢注意力。
 *   挪到角落 + 小号字，信息还在，但不抢。
 *
 * 判断标准：
 *   遮罩开着截图，**中央那块只有遮罩本身**。
 *   任何别的东西出现在那里，就是违反了这条。
 *
 * ⚠ 教训（2026-11-01）：这条我第一版写成「层级表」，
 *   结果自己按它挪位置时把提示压到状态面板上 ——
 *   层级表只说「谁在上面」，**没说「谁不能碰谁」**。
 *   所以补上最后那句「中央只有遮罩」，它才是可验证的。
 */


/* 铁律一 [AD-01]：用剪影确认身份。
 * 执行：把怪物主体填黑，缩到 32×32，与其它怪并排观察。
 * 验收：靠轮廓、姿态与地标仍能分辨；不能只靠颜色、名字或特效认怪。
 * 跳脸虫等屏幕空间演出采用对应的演出尺寸，不硬套世界实体比例。
  * 状态变体同样要用剪影确认（原 AD-51）：
 *   未激活／激活、待机／追击这类变体，至少改一项**剪影层面**的东西 ——
 *   姿态、比例、部件方向、开口、外扩形状。颜色与亮度只作辅助，
 *   不能作为唯一区分（诱饵玩偶原来只差亮度，暗场里分不出它在不在叫）。
 *   验收：缩到实际呈现尺寸 1/3、去掉颜色只剩剪影，仍能说出两个状态。
*/

/* 铁律二 [AD-02]：地标、负空间与不对称必须服务于角色。
 * 执行：为新怪确定独有的轮廓地标，保留肢体与躯干之间的可读空隙。
 * 验收：地标在实际游玩距离可辨；不对称有重心／动作依据。
 * 已获认可的怪物不为满足形式要求而强行改脸、加角或改变轮廓。
  * 负空间必须是**设计出来的**，不能是漏出来的（原 AD-54）：
 *   两个部件之间只要出现裸背景缺口，二选一：
 *     · 封住（下摆／横档／接缝）
 *     · 做成有意的形状（一条带描边的缝、一道暗槽）
 *   绝不允许"既没封、也不成形"。玩家会把这种缺口读成"模型破了"，
 *   而不是"这里本来就该是空的"（用户原话：身体下面那个小黑点）。
*/

/* 铁律三 [AD-03]：控制主要特征数量。
 * 执行：先写清 1—3 个相互独立的主要特征，再添加材质与次要细节。
 * 验收：缩小后仍先读到主要特征，装饰不抢戏；不要求为凑数硬加三个。
 */

/* 铁律四 [AD-04]：体态表达运动方式，速度以运行时为准。
 * 执行：用负重、前倾、拖曳、站姿解释它怎样移动；检查巡逻与追逐状态。
 * 验收：视觉重量、动作节奏与真实运动相符。体型不是固定速度公式。
 * 历史文档中的速度只作背景，当前值读实体查询函数与实际状态。
 */

/* 铁律五 [AD-05]：保持本作的恐怖基调。
 * 执行：主体克制、暗色、中性材质；让异常比例与关键部件承担恐怖感。
 * 验收：不是用一身荧光、卡通表情或无关装饰代替角色设计。
 * 听声怪与追光怪是已认可基准；不得因“恐怖不能有一对眼睛”而推翻它们。
 */

/* 当前造型基准：保留用户认可的识别点，改造前与 sprites.c 核对。
 *   听声怪：瘦高、无眼、牙齿下颌；冷灰蓝主体。
 *   追光怪：更细长、明显的亮眼；保留原有辨识度。
 *   爆脸虫：屏幕空间 QTE 演出，保留独立形态与提示。
 *   拾荒者：偏肩大麻袋、短腿、负重姿态、独眼；财物状态改局部。
 *   清道夫：长臂、驼背、细长外翻腿、无眼；姿态具有拖曳感。
 *   守门人：以后来认可的 v3 为准——尖顶、双角肩／收腰长袍、长提灯杖；
 *           巡逻脸的竖排三眼与追逐脸的独立变体分别核对。
 * 旧稿中的“横排三眼、桶状身体”不是当前守门人的设计目标。
 */

/* 铁律七 [AD-07]：用明暗解释厚度与材质。
 * 执行：按物件使用 ArtBevelK、ArtRecessK、透视收敛、局部受光等方法。
 * 验收：缩小后仍有前后层次；圆桶有圆柱受光，木箱有板缝，机柜有内凹。
 * 不是所有东西都适合斜角；同一种明暗模板不能替代不同的材质结构。
 */

/* 铁律八 [AD-08]：渐变适应像素密度。
 * 执行：大面积雾、光柱等优先评估 ArtBayer4 / ArtDitherOn 的有序抖动。
 * 验收：在最终呈现尺寸不糊、不闪、不产生抢眼噪点；硬边小物件保持清晰。
 * 抖动是手段，不是所有渐变都必须抖动；以实际画面读感为准。
 */

/* 铁律九 [AD-09]：威胁与资源采用不同的可读性预算。
 * 执行：怪物与道具分别走 ArtMonsterLight / ArtPropLight，参数看 art.c。
 * 验收：近处能辨识，远处自然融入黑暗；任务物不能暗到无法找到。
 * 检查出生点、普通走廊、近距离、远距离、低理智与手电开／关。
 * 世界黑暗不能吞掉必要的交互提示、出口选项和资源数量。
 */

/* 铁律十 [AD-10]：优化受光时保留已认可的形状。
 * 执行：先读 BakeProp / BakeMonster，再在相应材质区域增加受光与纹理。
 * 验收：同视角的新旧图能认出“同一个东西，层次更清楚了”。
 * 需要重做形状时明确说明造型目标；不能借加立体感把桶、箱子、机柜都换成盒子。
 */

/* 铁律十一 [AD-11]：尺度、像素密度与坐标空间一起核对。
 * 执行：比较角色、箱子、藏身点、电闸与出口的世界比例；核对实际 halfH。
 * 验收：同场大小关系稳定，分辨率变化不让某个物件突然像另一种尺度。
 * UI 另行区分客户区、内部 renderW/renderH、逻辑布局和鼠标坐标。
 * 不假设 winW/winH 永远等于客户区；绘制、测量与 MouseToLogical 使用相容变换。
 */


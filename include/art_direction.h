/* 铁律十八 [AD-18]：同一含义有唯一权威来源。
 * 执行：carryGold 与 bankGold 是金币的两个位置，状态不同，不能强并成一个变量。
 * 扣款、结算、被偷走钱包接口；UI 读实际状态，不维护另一套可漂移的“显示余额”。
 * 验收：开局、购买、死亡、撤离与读档后，显示的金额和可执行操作一致。
 * 测试要验证金额变化及失败无副作用；只搜函数名不能证明接线与逻辑正确。
 */

/* 铁律十九 [AD-19]：主题使用语义色，迁移范围必须说清。
 * 执行：先选 UI_INK / UI_* 主题色或现有 PAL_* 兼容语义色，再决定透明度。
 * 正文、背景、边框、状态、装饰各有职责；不能要求整张界面只有五种颜色。
 * 验收：同类信息跨页面含义一致，正文读得清，焦点与不可用状态可辨。
 * 当前仍有历史颜色字面量和两套色名；这是待迁移项，不宣称已经全量统一。
 * 调色以明确的局部迁移为单位，不在整理规范时顺带重染所有页面。
 */


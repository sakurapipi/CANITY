/* 铁律二十 [AD-20]：保留可恢复的修改边界。
 * 执行：先备份待改文件、记录已有未提交改动，再做有上下文的局部修改。
 * 验收：只撤销自己的改动；本项目不能用 git checkout / git restore 覆盖现有工作。
 * 文本替换须核对预期位置／次数，但不是强制只能用一种编辑工具。
 */

/* 铁律二十一 [AD-21]：布局、绘制与命中共用几何。
 * 执行：侧栏边界、内容起点、行高、详情区与返回入口从同一布局结果派生。
 * 验收：RowRect 不压 PageTabRect；文字在内容区内；看到的节点能在同处点中。
 * 切页时容器稳定；需要滚动／缩放时，显示范围、命中与导航同步变换。
 * 不能只改 RowRect，却让另一条独立绘制路径继续使用旧坐标。
 */

/* 铁律二十二 [AD-22]：内容表完整，新增项不会静默消失。
 * 执行：关键定义使用推导长度数组，加编译期数量断言；避免固定长度零填充漏项。
 * 本地／Steam 成就共用 achievement_defs.inc，数量、ID、名称与奖励不另抄一份。
 * 验收：每项有有效内容、入口与状态；不能靠 sizeof(显式长度数组) 判断填了多少项。
 */

/* 铁律二十三 [AD-23]：读档也是体验验收的一部分。
 * 执行：新增进度先核对存档结构，保留 v25 前缀，追加 v26 扩展并验证迁移。
 * 验收：启动恢复、继续对局、结算后重开分别检查；成就／图鉴揭示不因打开页面丢失。
 * 日期目标保存日期与计数基线；界面不能显示已经失效的昨天任务进度。
 * 测试写 CANITY_DATA_DIR 隔离目录；不能为了截好看的图污染玩家金币与存档。
 */

/* 铁律二十四 [AD-24]：音乐与提示音通过协议协调。
 * 执行：游戏发场景／暂停／重要事件，music.c 调度曲目与音量，audio.c 管音效。
 * Steam API 只经 steam_zone.c；未来 SIM 经 music.h 的版本化 provider 接入。
 * 验收：重要提示听得清，duck 到时恢复，暂停／恢复有效；缺曲目仍可运行。
 * 接口／模拟适配器通过测试，不等于 Steam、SIM 或实际歌曲已经联调通过。
 */

